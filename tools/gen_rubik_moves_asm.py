
#!/usr/bin/env python3
"""Generate precomputed R, B, D move tables for RV32I."""

from pathlib import Path

SOURCE = [
    [1, 4, 2, 0, 3, 5, 6],  # R
    [0, 1, 2, 4, 5, 6, 3],  # B
    [0, 2, 5, 3, 1, 4, 6],  # D
]

TWIST = [
    [1, 2, 0, 2, 1, 0, 0],
    [0, 0, 0, 1, 2, 1, 2],
    [0, 0, 0, 0, 0, 0, 0],
]


def compose(perm, orient, face):
    """Apply one clockwise face turn to a transformation."""
    src = SOURCE[face]
    tw = TWIST[face]

    new_perm = [perm[src[i]] for i in range(7)]
    new_orient = [
        (orient[src[i]] + tw[i]) % 3
        for i in range(7)
    ]

    return new_perm, new_orient


def generate():
    permutations = []
    orientations = []

    for face in range(3):
        perm = list(range(7))
        orient = [0] * 7

        for _power in range(3):
            perm, orient = compose(perm, orient, face)
            permutations.append(perm)
            orientations.append(orient)

        # Four quarter turns must return to identity.
        p4, o4 = compose(perm, orient, face)
        assert p4 == list(range(7))
        assert o4 == [0] * 7

    assert len(permutations) == 9
    assert len(orientations) == 9

    names = ["R", "R2", "R'", "B", "B2",
             "B'", "D", "D2", "D'"]

    lines = [
        "# Generated by tools/gen_rubik_moves_asm.py",
        "    .section .rodata",
        "    .balign 4",
        "rubik_move_source:",
    ]

    for name, values in zip(names, permutations):
        lines.append(
            "    .byte " + ", ".join(map(str, values))
            + f"    # {name}"
        )

    lines.extend([
        "    .balign 4",
        "rubik_move_twist:",
    ])

    for name, values in zip(names, orientations):
        lines.append(
            "    .byte " + ", ".join(map(str, values))
            + f"    # {name}"
        )

    root = Path(__file__).resolve().parents[1]
    output = root / "src/rubik/rubik_moves.inc"

    output.write_text(
        "\n".join(lines) + "\n",
        encoding="utf-8",
    )

    print(f"Generated {output}")
    print("9 moves, 63 source bytes, 63 twist bytes")


if __name__ == "__main__":
    generate()
