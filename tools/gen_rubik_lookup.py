
#!/usr/bin/env python3

from collections import deque
from pathlib import Path

# Must match src/rubik/rubik.c exactly.
SOURCE = (
    (1, 4, 2, 0, 3, 5, 6),  # R
    (0, 1, 2, 4, 5, 6, 3),  # B
    (0, 2, 5, 3, 1, 4, 6),  # D
)

TWIST = (
    (1, 2, 0, 2, 1, 0, 0),
    (0, 0, 0, 1, 2, 1, 2),
    (0, 0, 0, 0, 0, 0, 0),
)

FACTORIAL = (720, 120, 24, 6, 2, 1, 1)

MAX_DEPTH = 5
NUM_STATES = 5040 * 729

SOLVED = (
    (0, 1, 2, 3, 4, 5, 6),
    (0, 0, 0, 0, 0, 0, 0),
)


def turn(cube, face):
    p, o = cube

    next_p = tuple(p[SOURCE[face][i]] for i in range(7))

    next_o = tuple(
        (o[SOURCE[face][i]] + TWIST[face][i]) % 3
        for i in range(7)
    )

    return next_p, next_o


def apply_move(cube, move):
    face = move // 3
    turns = move % 3 + 1

    for _ in range(turns):
        cube = turn(cube, face)

    return cube


def permutation_rank(p):
    rank = 0

    for i in range(7):
        smaller = sum(p[j] < p[i] for j in range(i + 1, 7))
        rank += smaller * FACTORIAL[i]

    return rank


def orientation_code(o):
    code = 0

    for i in range(6):
        code = code * 3 + o[i]

    return code


def encode_state(cube):
    p, o = cube
    return permutation_rank(p) * 729 + orientation_code(o)


def build_layers():
    layers = [[] for _ in range(MAX_DEPTH + 1)]

    visited = bytearray(NUM_STATES)
    queue = deque([(SOLVED, 0)])

    solved_id = encode_state(SOLVED)
    visited[solved_id] = 1

    while queue:
        cube, depth = queue.popleft()

        state_id = encode_state(cube)
        layers[depth].append(state_id)

        if depth == MAX_DEPTH:
            continue

        for move in range(9):
            next_cube = apply_move(cube, move)
            next_id = encode_state(next_cube)

            if visited[next_id]:
                continue

            visited[next_id] = 1
            queue.append((next_cube, depth + 1))

    for layer in layers:
        layer.sort()

    return layers


def write_header(layers, output):
    all_ids = []
    offsets = [0]

    for layer in layers:
        all_ids.extend(layer)
        offsets.append(len(all_ids))

    packed = bytearray()

    for state_id in all_ids:
        packed.append(state_id & 0xFF)
        packed.append((state_id >> 8) & 0xFF)
        packed.append((state_id >> 16) & 0xFF)

    with output.open("w", encoding="utf-8") as f:
        f.write("/* Generated by tools/gen_rubik_lookup.py. */\n")
        f.write("#ifndef RUBIK_LOOKUP_H\n")
        f.write("#define RUBIK_LOOKUP_H\n\n")
        f.write("#include <stdint.h>\n\n")

        f.write("static const uint32_t lookup_offsets[7] = {\n    ")
        f.write(", ".join(str(x) for x in offsets))
        f.write("\n};\n\n")

        f.write(
            f"static const uint8_t lookup_packed[{len(packed)}] = {{\n"
        )

        for i in range(0, len(packed), 12):
            chunk = packed[i:i + 12]
            f.write("    ")
            f.write(", ".join(f"0x{x:02x}" for x in chunk))
            f.write(",\n")

        f.write("};\n\n")
        f.write("#endif\n")

    return len(all_ids), len(packed)


def main():
    # Sanity checks against our known states.
    assert encode_state(SOLVED) == 0

    after_r = apply_move(SOLVED, 0)
    assert encode_state(after_r) == 805242

    layers = build_layers()

    assert len(layers[0]) == 1
    assert len(layers[1]) == 9
    assert 805242 in layers[1]

    output = Path("src/rubik/rubik_lookup.h")
    count, size = write_header(layers, output)

    print("===== Lookup Table Summary =====")

    for depth, layer in enumerate(layers):
        print(f"Depth {depth}: {len(layer)} states")

    print(f"Total entries: {count}")
    print(f"Packed data: {size} bytes")
    print(f"Packed data: {size / 1024:.2f} KiB")
    print(f"Output: {output}")


if __name__ == "__main__":
    main()
